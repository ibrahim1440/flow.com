/**
 * How a deal is named where a rep picks one (D21, owner-approved Figma 2000:2, 10 Nov 2026 — wording أ).
 *
 * A deal's stored title is often generated from the customer's name — «مؤسسة … — عرض سعر 2026-11-06», «طلب مباشر — …»,
 * «… · عرض المحاسب Q-12», or just the company name a lead was converted with — so in a list of ONE customer's deals it
 * repeats that name and is cut on a phone. Instead:
 *   · a generated title → line 1 «عرض سعر · 644.00 ⃁ · 6 نوفمبر» (type · amount · date), line 2 «المرحلة: تفاوض»;
 *   · a title someone wrote → line 1 the title, line 2 «عرض سعر · 644.00 ⃁ · 6 نوفمبر · تفاوض».
 * No amount (0 or none): the amount is left out. The year is shown only when it is not the current one.
 * Pure — used by the customer page's «سجّل نشاط», «عرض السعر على أي صفقة؟» and the «سجّل نشاط» record picker.
 */
import { withRiyal } from "@/lib/money/riyal";

export type DealLabelInput = {
  title: string;
  amount?: string | number | null;
  createdAt?: string | Date | null;
  stageAr?: string | null;
  stageEn?: string | null;
  quotes?: number | null;
  samples?: number | null;
  /** D21 L2: the deal's latest quotation date — a quote deal is dated by its quotation, not by when the deal was opened. */
  quoteAt?: string | Date | null;
};
export type DealKind = "quote" | "sample" | "direct" | "deal";
export type DealLabel = { label: string; hint: string; custom: boolean; kind: DealKind };

/** The «لا» first option of «تربطه بصفقة؟» (wording أ). */
export const NO_DEAL_LABEL = { ar: "لا — العميل بشكل عام", en: "No — the customer in general" } as const;

const KIND: Record<DealKind, { ar: string; en: string }> = {
  quote: { ar: "عرض سعر", en: "Quotation" },
  sample: { ar: "عيّنة", en: "Sample" },
  direct: { ar: "طلب مباشر", en: "Direct order" },
  deal: { ar: "صفقة", en: "Deal" },
};

const squash = (s: string) => s.replace(/\s+/g, " ").trim();
const DATE_TAIL = String.raw`(?:\d{4}-\d{2}-\d{2}|\d{2}-\d{2}-\d{4})`;

/**
 * Was this title generated by the system (from the customer's name), and of which kind? D21 L1: when the customer's names
 * are known, the generated shapes must START with one of them — «تجربة محاصيل الشتاء — عرض سعر 2026-11-06» written by a rep
 * is the rep's title and is kept. Without names (no customer on hand) the shape alone decides, as before.
 */
export function generatedKind(title: string, customerNames: (string | null | undefined)[] = []): DealKind | null {
  const t = squash(title);
  if (!t) return "deal";
  const names = customerNames.filter((n): n is string => !!n && !!n.trim()).map(squash);
  const esc = (x: string) => x.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const who = names.length ? `(?:${names.map(esc).join("|")})` : ".+";
  if (new RegExp(String.raw`^${who}\s—\sعرض سعر\s${DATE_TAIL}$`).test(t)) return "quote";
  if (new RegExp(String.raw`^${who}\s—\sعيّ?نة\s${DATE_TAIL}$`).test(t)) return "sample";
  if (new RegExp(String.raw`^طلب مباشر\s—\s${who}$`).test(t)) return "direct";
  if (new RegExp(String.raw`^${who}\s·\sعرض المحاسب\s\S+$`).test(t)) return "quote";
  if (names.some((n) => n === t)) return "deal";
  return null;
}

/** D21 L2: the day a generated «… — عرض سعر 2026-11-06» title carries (the deal's own date for the rep). */
function titleDay(title: string): Date | null {
  const m = squash(title).match(/(\d{4})-(\d{2})-(\d{2})$/) ?? squash(title).match(/(\d{2})-(\d{2})-(\d{4})$/);
  if (!m) return null;
  const [y, mo, d] = m[1].length === 4 ? [m[1], m[2], m[3]] : [m[3], m[2], m[1]];
  const at = new Date(`${y}-${mo}-${d}T12:00:00+03:00`);
  return Number.isNaN(at.getTime()) ? null : at;
}

function kindFromCounts(d: DealLabelInput): DealKind {
  if ((d.quotes ?? 0) > 0) return "quote";
  if ((d.samples ?? 0) > 0) return "sample";
  return "deal";
}

function money(amount: DealLabelInput["amount"], lang: "ar" | "en"): string | null {
  const n = typeof amount === "string" ? Number(amount) : amount ?? 0;
  if (!Number.isFinite(n) || n <= 0) return null;
  const f = new Intl.NumberFormat("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(n);
  return withRiyal(f, lang);
}

function day(d: DealLabelInput["createdAt"], lang: "ar" | "en", now: Date): string | null {
  if (!d) return null;
  const at = new Date(d);
  if (Number.isNaN(at.getTime())) return null;
  const year = (x: Date) => new Intl.DateTimeFormat("en-US", { timeZone: "Asia/Riyadh", year: "numeric" }).format(x);
  const sameYear = year(at) === year(now);
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-SA-u-nu-latn-ca-gregory" : "en-GB", {
    timeZone: "Asia/Riyadh", day: "numeric", month: lang === "ar" ? "long" : "short", ...(sameYear ? {} : { year: "numeric" }),
  }).format(at);
}

/** «عرض سعر · 644.00 ⃁ · 6 نوفمبر» alone — for a row that names the customer itself (the «سجّل نشاط» record picker). */
export function dealFacts(d: DealLabelInput, opts: { lang: "ar" | "en"; customerNames?: (string | null | undefined)[]; now?: Date }): { facts: string; generated: boolean } {
  const gen = generatedKind(d.title, opts.customerNames);
  const kind: DealKind = gen && gen !== "deal" ? gen : kindFromCounts(d);
  // D21 L2: the date the rep knows the deal by — the generated title's own day, else a quote deal's quotation, else its opening.
  const when = (gen && gen !== "deal" ? titleDay(d.title) : null) ?? (kind === "quote" && d.quoteAt ? d.quoteAt : null) ?? d.createdAt;
  return { facts: [KIND[kind][opts.lang], money(d.amount, opts.lang), day(when, opts.lang, opts.now ?? new Date())].filter(Boolean).join(" · "), generated: gen !== null };
}

/** The two lines of a deal in a picker. `customerNames`: the customer's names, so a title that is just the name counts as generated. */
export function dealLabel(d: DealLabelInput, opts: { lang: "ar" | "en"; customerNames?: (string | null | undefined)[]; now?: Date }): DealLabel {
  const { lang } = opts;
  const now = opts.now ?? new Date();
  const gen = generatedKind(d.title, opts.customerNames);
  // The generated title says the kind; a bare name (a converted lead) or a written title leaves it to the deal's documents.
  const kind: DealKind = gen && gen !== "deal" ? gen : kindFromCounts(d);
  const { facts } = dealFacts(d, { lang, customerNames: opts.customerNames, now });
  const stage = (lang === "ar" ? d.stageAr : d.stageEn) ?? d.stageAr ?? d.stageEn ?? null;
  if (gen) return { label: facts, hint: stage ? (lang === "ar" ? `المرحلة: ${stage}` : `Stage: ${stage}`) : "", custom: false, kind };
  return { label: squash(d.title), hint: [facts, stage].filter(Boolean).join(" · "), custom: true, kind };
}
